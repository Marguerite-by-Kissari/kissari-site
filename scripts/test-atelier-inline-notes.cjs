const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const fields = Object.fromEntries(['title','subtitle','author','category','image','creation-date','publication-date','publication-time','publication-status','intro','next-teaser'].map(id => ['#'+id,{value:''}]));
fields['#title'].value='Test notes';
fields['#intro'].value='Un mot[^note-test] dans le texte.';
fields['#publication-date'].value='2026-11-12';
fields['#publication-time'].value='09:00';
const context = vm.createContext({window:{KissariPublication:require('../static/atelier-article/publication-date.js')},document:{querySelector:s=>fields[s]},console});
const source=fs.readFileSync('static/atelier-article/app.js','utf8').split('const syncForm=')[0];
vm.runInContext(source,context);
vm.runInContext("state.notes={'note-test':'Une **précision**.\\nSeconde ligne.'}; state.blocks=[];",context);
const output=vm.runInContext('markdown()',context);
assert.ok(output.includes('Un mot[^note-test] dans le texte.'),'reference must stay attached to selected word');
assert.ok(output.includes('[^note-test]: Une **précision**.\n    Seconde ligne.'),'inline note definition must be exported with multiline indentation');
assert.ok(!output.includes('\n\n[^note-test]\n'),'no isolated reference paragraph');
console.log('PASS attached inline note and multiline Markdown definition');
const preview=vm.runInContext("inlineBold('Un mot[^note-test] et **du gras** <script>')",context);
assert.ok(preview.includes('class="preview-note-ref"'),'inline note must become a clickable preview reference');
assert.ok(preview.includes('<strong>du gras</strong>'));
assert.ok(preview.includes('&lt;script&gt;'),'author HTML must stay escaped');
assert.ok(!preview.includes('[^note-test]'));
console.log('PASS clickable reference, bold and escaped HTML');
vm.runInContext("state.notes['note-orphan']='Must not export';",context);
assert.ok(!vm.runInContext('markdown()',context).includes('Must not export'));
vm.runInContext("state.blocks=[{type:'paragraph',body:'Again[^note-test].'},{type:'footnote',body:'Legacy note.'}];",context);
const mixed=vm.runInContext('markdown()',context);
assert.equal((mixed.match(/\[\^note-test\]:/g)||[]).length,1,'one definition per used note');
assert.ok(mixed.includes('[^1]: Legacy note.'),'old note blocks remain exportable');
assert.ok(vm.runInContext('payload().notes["note-test"]',context));
vm.runInContext('renderBlocks=()=>{};renderPreview=()=>{};apply({fields:{},blocks:[]});',context);
assert.equal(vm.runInContext('Object.keys(state.notes).length',context),0,'legacy drafts default to an empty note map');
console.log('PASS orphan omission, duplicate reference, legacy notes, payload and old drafts');
vm.runInContext("state.notes={'note-b':'Deuxième créée, première citée.','note-a':'Première créée, deuxième citée.'};state.blocks=[];",context);
fields['#intro'].value='Premier[^note-b], deuxième[^note-a], rappel[^note-b].';
const numbered=vm.runInContext("inlineBold(val('intro'))",context);
assert.deepEqual([...numbered.matchAll(/class="preview-note-ref"[^>]*>(\d+)<\/a>/g)].map(m=>m[1]),['1','2','1']);
const refIDs=[...numbered.matchAll(/id="(ref-[^"]+)"/g)].map(m=>m[1]);
assert.equal(new Set(refIDs).size,3,'each occurrence has a unique return target');
console.log('PASS numeric preview, citation-order numbering and repeated-reference IDs');
